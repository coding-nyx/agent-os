let registered = false;

function logAuditTrail(event: SpineEvent) {
  void AuditTrail.logAction({
    agent_source: event.source,
    action_summary: `${event.type} observed`,
    raw_payload: JSON.stringify(event.data ?? {}),
    soul_snapshot: '',
  });
}

export function registerFlowConsumers(): void {
  if (registered) return;
  registered = true;

  FLOW_EVENTS.forEach((eventType) => {
    Spine.on(eventType, logAuditTrail);
  });
}
